 class whileloop {
    public static void main(String[] args) {
        
        //Print numbers from 1 to 5
        int i=1;
        while(i<=5){
            System.out.println(i);
            i++;
        }
        //Print numbers from 10 to 1 (Reverse)
        int i=10;
        while(i>=10){
            System.out.println(i);
            i--;
        }
        
        //Print even numbers from 1 to 20
         int j =2;
         while(j<=20){
           System.out.println(j);
           j+=2;
         }


    
    
    
        }

    
}
