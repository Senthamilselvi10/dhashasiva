 class squarepattern {
    public static void main(String[] args) {
        //square pattern
        for(int i=1;i<=4;i++){
           for(int j=1;j<=4;j++){
           System.out.print("*");
    }
        System.out.println();
}
// right triangle
for(int i=1;i<=5;i++){
    for(int j=1;j<=i;j++){
        System.out.print("*");
    }
        System.out.println();
}

      
    //inverted right triangle
    for(int i=5;i>=1;i--){
        for(int j=1;j<=i;j++){
            System.out.print("*");
        }
        System.out.println();
    }
    






}    
}
